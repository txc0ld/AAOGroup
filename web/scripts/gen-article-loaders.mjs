import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";

const contentDir = path.join(process.cwd(), "content/articles");
const outFile = path.join(process.cwd(), "app/articles/loaders.generated.ts");
const mdOutDir = path.join(process.cwd(), "public/articles");

// Apex base URL (matches lib/business.ts + public/llms.txt). Build-time constant.
const BASE = "https://operateai.com.au";

const files = fs.existsSync(contentDir)
  ? fs
      .readdirSync(contentDir)
      .filter((f) => f.endsWith(".mdx"))
      .sort()
  : [];

const slugs = files.map((f) => f.replace(/\.mdx$/, ""));

// --- 1. Loader map (unchanged behaviour) -----------------------------------
const body = [
  "// AUTO-GENERATED by scripts/gen-article-loaders.mjs — do not edit by hand.",
  "// Run `pnpm articles:gen` after adding or removing an article .mdx file.",
  'import type React from "react";',
  "",
  "export const LOADERS: Record<string, () => Promise<{ default: React.ComponentType }>> = {",
  ...slugs.map((s) => `  ${JSON.stringify(s)}: () => import(${JSON.stringify(`@/content/articles/${s}.mdx`)}),`),
  "};",
  "",
].join("\n");

fs.writeFileSync(outFile, body);

// Slug list as its own module so proxy.ts (edge) can import it without
// pulling the MDX dynamic imports into the proxy bundle.
const slugsFile = path.join(process.cwd(), "app/articles/slugs.generated.ts");
fs.writeFileSync(
  slugsFile,
  [
    "// AUTO-GENERATED by scripts/gen-article-loaders.mjs — do not edit by hand.",
    "// Run `pnpm articles:gen` after adding or removing an article .mdx file.",
    "",
    `export const ARTICLE_SLUGS: readonly string[] = ${JSON.stringify(slugs, null, 2)};`,
    "",
  ].join("\n"),
);

// --- 2. Agent-readable .md twins -------------------------------------------
// Every article gets a clean Markdown copy at /articles/<slug>.md so AI agents
// and crawlers can read the content without parsing the rendered HTML.

// Turn the MDX body into plain Markdown: drop decorative JSX component lines
// (they carry no text), strip any import/export lines, absolutise root-relative
// links so the file is self-contained, and tidy up blank runs.
function toPlainMarkdown(mdxBody) {
  let inFence = false;
  const out = [];
  for (const line of mdxBody.split("\n")) {
    const t = line.trim();
    if (/^(```|~~~)/.test(t)) {
      inFence = !inFence;
      out.push(line);
      continue;
    }
    if (inFence) {
      out.push(line); // never transform inside code fences
      continue;
    }
    if (/^import\s/.test(t) || /^export\s/.test(t)) continue; // MDX JS
    if (/^<\/?[A-Z][A-Za-z0-9]*(\s[^>]*)?\/?>$/.test(t)) continue; // <Component /> on its own line
    out.push(line.replace(/\]\(\/(?!\/)/g, `](${BASE}/`)); // [text](/path) -> absolute
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

const meta = []; // for the index

fs.mkdirSync(mdOutDir, { recursive: true });

for (const file of files) {
  const slug = file.replace(/\.mdx$/, "");
  const raw = fs.readFileSync(path.join(contentDir, file), "utf8");
  const { data, content } = matter(raw);
  const fm = data ?? {};
  const canonical = `${BASE}/articles/${slug}/`;

  const dateLine = [
    fm.author ? `By ${fm.author}` : null,
    fm.date ? `Published ${fm.date}` : null,
    fm.updated && fm.updated !== fm.date ? `Updated ${fm.updated}` : null,
  ]
    .filter(Boolean)
    .join(" · ");

  const takeaways = Array.isArray(fm.takeaways) ? fm.takeaways : [];

  const header = [
    `# ${fm.title ?? slug}`,
    "",
    fm.description ? `> ${fm.description}` : null,
    "",
    dateLine || null,
    `Source: ${canonical}`,
    `Publisher: OperateAI — AI search visibility for Perth local service businesses`,
    "",
    ...(takeaways.length
      ? ["## Key takeaways", "", ...takeaways.map((t) => `- ${t}`), ""]
      : []),
    "---",
    "",
  ]
    .filter((l) => l !== null)
    .join("\n");

  const md = `${header}${toPlainMarkdown(content)}\n`;
  fs.writeFileSync(path.join(mdOutDir, `${slug}.md`), md);

  meta.push({
    slug,
    title: fm.title ?? slug,
    description: fm.description ?? "",
    date: fm.date ?? "",
    canonical,
  });
}

// --- 3. Machine-readable article index -------------------------------------
meta.sort((a, b) => (a.date < b.date ? 1 : -1));

const index = [
  "# OperateAI — Articles (Markdown for agents)",
  "",
  "> Plain-Markdown copies of every OperateAI article, for AI agents and crawlers.",
  "> Each article's Markdown twin lives at /articles/<slug>.md. Human pages are at /articles/<slug>/.",
  "",
  ...meta.flatMap((a) => [
    `## ${a.title}`,
    a.description ? a.description : null,
    `- Markdown: ${BASE}/articles/${a.slug}.md`,
    `- Page: ${a.canonical}`,
    a.date ? `- Published: ${a.date}` : null,
    "",
  ].filter((l) => l !== null)),
].join("\n");

fs.writeFileSync(path.join(mdOutDir, "index.md"), index + "\n");

console.log(
  `articles:gen → ${slugs.length} loader(s) + ${files.length} .md twin(s) + index.md written`,
);
